//! Part 2: each new rule / construct has a failing-input test (and a passing twin where it helps).

use pvc_ir::diag::Edit;
use pvc_ir::*;

const H: &str = "pvc 0.1 use std@0.1 theme light\nfonts std\n";
fn run(body: &str) -> Vec<Diagnostic> {
    match compile_terse(&format!("{}{}", H, body)) {
        Ok(c) => c.diagnostics,
        Err(d) => d,
    }
}
fn codes(d: &[Diagnostic]) -> Vec<&str> {
    d.iter().map(|x| x.code).collect()
}
fn has<'a>(d: &'a [Diagnostic], code: &str, key: &str) -> &'a Diagnostic {
    d.iter()
        .find(|x| x.code == code && x.message_key == key)
        .unwrap_or_else(|| panic!("no {code}/{key} in {:#?}", d.iter().map(|x| x.render()).collect::<Vec<_>>()))
}
fn clean(body: &str) {
    let d = run(body);
    assert!(d.is_empty(), "{:#?}", d.iter().map(|x| x.render()).collect::<Vec<_>>());
}

#[test]
fn a11y_img_shape_and_avatar_need_a_name_or_decorative() {
    let d = run("shape circle w=12 h=12\n");
    let x = has(&d, "PVC-E-A11Y-IMG", "a11y.image-unnamed");
    assert!(x.fixes.iter().any(|f| f.key == "set-alt") && x.fixes.iter().any(|f| f.key == "mark-decorative"));
    clean("shape circle w=12 h=12 decorative\n");
    clean("shape circle w=12 h=12 alt=\"A dot\"\n");
}

