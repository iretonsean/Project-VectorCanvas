#[test]
fn eval_semantics_decimal_percent_and_aggregates() {
    use pvc_ir::eval::*;
    let m = parse_terse(&format!(
        "{H}state {{ l: list(p:decimal, q:int) max=5 = [{{ p=0.05 q=3 }}, {{ p=1.50 q=1 }}] ; z: list(p:decimal) max=2 }}\nderive s = sum(l, it.p * it.q)\nderive e = sum(z, it.p)\ntext \"x\"\n"
    ))
    .unwrap();
    let st = State::init(&m);
    let ev = |e: Expr| eval(&m, &st, &e).unwrap();
    assert_eq!(ev(Expr::Var("s".into())), Value::Decimal(165));
    assert_eq!(ev(Expr::Var("e".into())), Value::Decimal(0), "empty decimal sum stays decimal");
    let pct = |x: i64, p: Expr| ev(Expr::Call(Func::Percent, vec![Expr::Dec(x), p]));
    assert_eq!(pct(1, Expr::Int(50)), Value::Decimal(1), "0.5 cent rounds half up to 1");
    assert_eq!(pct(5, Expr::Dec(1000)), Value::Decimal(1), "0.5 cent");
    assert_eq!(pct(4, Expr::Int(10)), Value::Decimal(0), "0.4 cent rounds down");
    assert_eq!(pct(2614, Expr::Dec(825)), Value::Decimal(216));
    assert_eq!(pct(-5, Expr::Int(10)), Value::Decimal(-1), "half away from zero");
    assert_eq!(format_value(&Value::Decimal(-5)), "-0.05");
    assert_eq!(format_value(&Value::Decimal(2614)), "26.14");
    assert_eq!(template_holes("a {x} {{b}} {y}"), Ok(vec!["x".to_string(), "y".to_string()]));
    assert_eq!(template_holes("{x"), Err(()));
}
