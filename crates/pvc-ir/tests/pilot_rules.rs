#[test]
fn links_need_a_target_and_hrefs_need_an_open_url_capability_in_scope() {
    let d = run("link \"Docs\"\n");
    has(&d, "PVC-E-A11Y-ACTION", "a11y.action-missing");
    let d = run("link \"Docs\" href=\"https://example.com/docs\"\n");
    let x = has(&d, "PVC-E-CAP-UNDECLARED", "cap.undeclared");
    assert!(matches!(&x.fixes[0].edit, Edit::AddLine { line } if line == "cap open-url.main urls=[\"https://example.com/\"]"));
    let d = run("cap open-url.main urls=[\"https://example.com/\"]\nlink \"Docs\" href=\"https://evil.test/x\"\n");
    has(&d, "PVC-E-CAP-SCOPE", "cap.scope");
    clean("cap open-url.main urls=[\"https://example.com/\"]\nlink \"Docs\" href=\"https://example.com/docs\"\n");
    // in-app links use a handler
    clean("state { b: bool }\nlink \"More\" on.press={ b = true }\n");
}

