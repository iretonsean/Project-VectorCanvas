#[test]
fn text_template_holes_and_args_must_agree() {
    // hole without arg
    let d = run("text @t\nstrings en { t \"{n} items\" }\n");
    has(&d, "PVC-E-REF", "ref.text-hole");
    // arg that is no hole (typo) -> nearest hole offered
    let d = run("state { n: int }\ntext @t m=(n)\nstrings en { t \"{n} items\" }\n");
    let x = has(&d, "PVC-E-REF", "ref.text-arg");
    assert!(matches!(&x.fixes[0].edit, Edit::Choose { candidates } if candidates.contains(&"n".to_string())));
    // unbalanced braces
    let d = run("text @t\nstrings en { t \"{n items\" }\n");
    has(&d, "PVC-E-SCHEMA", "schema.bad-template");
    clean("state { n: int }\ntext @t n=(n)\nstrings en { t \"{n} items, {{literal}}\" }\n");
}

#[test]
fn lists_views_and_row_actions_are_checked() {
    let st = "state { xs: list(a:int, t:text) max=3 }\n";
    clean(&format!("{st}view xs as=r {{ row {{ text value=(r.t); button \"Del\" on.press={{ remove r }} }} }}\n"));
    // unknown list
    let d = run("view ys as=r { text \"x\" }\n");
    has(&d, "PVC-E-REF", "ref.list");
    // unknown field of the row
    let d = run(&format!("{st}view xs as=r {{ text value=(r.zz) }}\n"));
    has(&d, "PVC-E-REF", "ref.field");
    // alias used outside its view
    let d = run(&format!("{st}text value=(r.t)\n"));
    has(&d, "PVC-E-REF", "ref.alias");
    // remove outside a view
    let d = run(&format!("{st}button \"x\" on.press={{ remove r }}\n"));
    has(&d, "PVC-E-REF", "ref.alias");
    // filter must be bool
    let d = run(&format!("{st}view xs as=r where=(r.a) {{ text \"x\" }}\n"));
    has(&d, "PVC-E-TYPE", "type.mismatch");
    // append: unknown field / wrong type / unknown list
    let d = run(&format!("{st}button \"x\" on.press={{ append xs {{ zz = 1 }} }}\n"));
    has(&d, "PVC-E-REF", "ref.field");
    let d = run(&format!("{st}button \"x\" on.press={{ append xs {{ a = \"s\" }} }}\n"));
    has(&d, "PVC-E-TYPE", "type.mismatch");
    let d = run(&format!("{st}button \"x\" on.press={{ append nope {{ a = 1 }} }}\n"));
    has(&d, "PVC-E-REF", "ref.list");
    // count/sum names must be lists
    let d = run("state { n: int }\ntext @t k=(count(n))\nstrings en { t \"{k}\" }\n");
    has(&d, "PVC-E-REF", "ref.list");
    // the list itself cannot be assigned
    let d = run(&format!("{st}button \"x\" on.press={{ xs = 1 }}\n"));
    assert!(codes(&d).contains(&"PVC-E-TYPE"));
}

#[test]
fn decimal_and_integer_arithmetic_typing() {
    clean("state { p: decimal = 1.50; q: int = 2 }\nderive t = p * q + 0.25\ntext @m v=(t)\nstrings en { m \"${v}\" }\n");
    let d = run("state { p: decimal = 1.50 }\nderive t = p * p\ntext \"x\"\n");
    has(&d, "PVC-E-TYPE", "type.decimal-times-decimal");
    let d = run("state { p: decimal; s: text }\nderive t = p + s\ntext \"x\"\n");
    has(&d, "PVC-E-TYPE", "type.mismatch");
    let d = run("state { p: int }\nderive t = percent(p, 5)\ntext \"x\"\n");
    has(&d, "PVC-E-TYPE", "type.mismatch");
    // more than 2 decimals is a parse error, not a silent rounding
    let d = compile_terse(&format!("{H}state {{ p: decimal = 1.005 }}\ntext \"x\"\n")).unwrap_err();
    assert!(d.iter().any(|x| x.code.starts_with("PVC-E-")), "{:?}", d.iter().map(|x| x.render()).collect::<Vec<_>>());
    let d = compile_terse(&format!("{H}state {{ p: decimal }}\nderive t = p + 1.005\ntext \"x\"\n")).unwrap_err();
    assert_eq!(d[0].code, "PVC-E-PARSE");
    // decimal literals in lists
    let m = parse_terse(&format!("{H}state {{ l: list(p:decimal) max=2 = [{{ p=2.5 }}] }}\ntext \"x\"\n")).unwrap();
    assert_eq!(m.state[0].init, Value::List(vec![vec![("p".into(), Value::Decimal(250))]]));
}

#[test]
fn list_initialiser_errors() {
    for bad in [
        "state { l: list(p:int) max=1 = [{ p=1 }, { p=2 }] }\n", // too many rows
        "state { l: list(p:int) max=2 = [{ q=1 }] }\n",           // unknown field
        "state { l: list(p:int, r:int) max=2 = [{ p=1 }] }\n",    // missing field
        "state { l: list(p:int) max=2 = [{ p=\"s\" }] }\n",       // wrong type
        "state { l: list(p:foo) max=2 }\n",                       // unknown field type
    ] {
        let d = compile_terse(&format!("{H}{bad}text \"x\"\n")).unwrap_err();
        assert!(d.iter().any(|x| x.is_error()), "{bad}: {:?}", d.iter().map(|x| x.render()).collect::<Vec<_>>());
    }
}

#[test]
fn slot_and_case_rules() {
    let st = "state { s: enum(a, b) }\n";
    clean(&format!("{st}slot on=s {{ case a {{ text \"A\" }}; case b {{ text \"B\" }} }}\n"));
    // incomplete: warning only
    let c = compile_terse(&format!("{H}{st}slot on=s {{ case a {{ text \"A\" }} }}\n")).unwrap();
    assert!(c.diagnostics.iter().any(|x| x.code == "PVC-W-SLOT-INCOMPLETE"));
    // unknown case value
    let d = run(&format!("{st}slot on=s {{ case a {{ }}; case b {{ }}; case zz {{ }} }}\n"));
    has(&d, "PVC-E-REF", "ref.variant");
    // non-case child, missing on, case outside slot, duplicate case
    let d = run(&format!("{st}slot on=s {{ text \"x\" }}\n"));
    has(&d, "PVC-E-SCHEMA", "schema.slot-child-not-case");
    let d = run("slot { case a { } }\n");
    has(&d, "PVC-E-SCHEMA", "schema.missing-field");
    let d = run("case a { }\n");
    has(&d, "PVC-E-SCHEMA", "schema.case-outside-slot");
    let d = run(&format!("{st}slot on=s {{ case a {{ }}; case a {{ }} }}\n"));
    has(&d, "PVC-E-ID-COLLISION", "id.duplicate-case");
    // slot on a bool
    clean("state { f: bool }\nslot on=f { case true { text \"y\" }; case false { text \"n\" } }\n");
    // slot on a text is a type error
    let d = run("state { t: text }\nslot on=t { case a { } }\n");
    has(&d, "PVC-E-TYPE", "type.mismatch");
}

#[test]
fn breakpoint_overrides_parse_and_are_validated() {
    let m = parse_terse(&format!("{H}grid cols=4 gap=md md.cols=2 sm.cols=1 sm.gap=xs md.show=true w=fill {{ text \"a\" }}\n")).unwrap();
    let g = &m.root.children[0];
    assert_eq!(g.layout.cols, 4);
    assert_eq!(g.at.len(), 2);
    assert_eq!((g.at[0].bp, g.at[0].patch.cols, g.at[0].show), (Bp::Md, Some(2), Some(true)));
    assert_eq!((g.at[1].bp, g.at[1].patch.cols, g.at[1].patch.gap), (Bp::Sm, Some(1), Some(Len::from_px(4))));
    // dir override on a row
    let m = parse_terse(&format!("{H}row md.dir=col md.w=fill {{ }}\n")).unwrap();
    assert_eq!(m.root.children[0].at[0].patch.dir, Some(Dir::Col));
    // errors
    let d = run("grid cols=2 md.colz=1 { }\n");
    has(&d, "PVC-E-SCHEMA", "schema.unknown-field");
    let d = run("grid cols=2 md.cols=0 { }\n");
    has(&d, "PVC-E-SCHEMA", "schema.bad-cols");
    let d = run("grid { }\n");
    has(&d, "PVC-E-SCHEMA", "schema.missing-field");
    let d = run("box md.dir=diagonal { }\n");
    has(&d, "PVC-E-SCHEMA", "schema.expected-choice");
    // sm applies at <= 480, md at <= 768
    assert_eq!((Bp::Md.max_width(), Bp::Sm.max_width()), (768, 480));
}

