#[test]
fn std_controls_added_in_part2() {
    // switch / radio / tab / list / item / link
    let m = parse_terse(&format!(
        "{H}state {{ a: bool; e: enum(x, y) }}\nswitch \"Wi-Fi\" bind=a\nradio \"X\" bind=e value=x\ntab \"T\" selected=(e == x) on.press={{ e = y }}\nlist {{ item {{ text \"i\" }} }}\n"
    ))
    .unwrap();
    let roles: Vec<Role> = m.root.children.iter().map(|n| n.sem.role).collect();
    assert_eq!(roles, [Role::Switch, Role::Radio, Role::Tab, Role::List]);
    assert_eq!(m.root.children[3].children[0].sem.role, Role::ListItem);
    // bare switch/checkbox need a name
    let d = run("state { a: bool }\nswitch bind=a\n");
    has(&d, "PVC-E-SCHEMA", "schema.missing-label");
    clean("state { a: bool }\nswitch name=\"Wi-Fi\" bind=a\ncheckbox name=\"Done\" bind=a\n");
    // radio needs a value, tab needs `selected`
    has(&run("state { e: enum(x, y) }\nradio \"X\" bind=e\n"), "PVC-E-SCHEMA", "schema.missing-field");
    has(&run("tab \"T\" on.press={ }\n"), "PVC-E-SCHEMA", "schema.missing-field");
    // button fill=none is the secondary look
    let m = parse_terse(&format!("{H}button \"B\" fill=none on.press={{ }}\n")).unwrap();
    assert!(m.root.children[0].paint.fill.is_none() && m.root.children[0].paint.border.is_some());
}

